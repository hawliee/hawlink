  assert.equal((await request('/api/board',{...opts,headers:{...opts.headers,Origin:'https://untrusted.example'}})).status,403);
  assert.equal((await request('/server.js')).status,404);
  assert.equal((await request('/uploads/..%2Fboard.json')).status,404);
  await new Promise(resolve=>app.close(resolve));
  app=await createApp({dataDir});await new Promise(resolve=>app.listen(0,'127.0.0.1',resolve));base=`http://127.0.0.1:${app.address().port}`;
